// Copies the font files the app needs from the @fontsource packages into public/fonts and writes
// styles/fonts.css. Run with `npm run fonts` after changing the list below; the output is committed,
// so a normal install or build never needs this script.
//
// The families are the ones on Google Fonts (SIL Open Font License). We serve them ourselves so the
// first paint does not wait on a second host, the offline kit can cache them, and a phone only
// downloads the script it is showing (each @font-face carries a unicode-range).

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = (pkg) => join(root, "node_modules", "@fontsource-variable", pkg);

/** family: the CSS name the app uses. subsets: which subset files to ship. */
const FONTS = [
  { pkg: "atkinson-hyperlegible-next", family: "Atkinson Hyperlegible Next", subsets: ["latin", "latin-ext"] },
  { pkg: "atkinson-hyperlegible-mono", family: "Atkinson Hyperlegible Mono", subsets: ["latin"] },
  { pkg: "noto-nastaliq-urdu", family: "Noto Nastaliq Urdu", subsets: ["arabic"] },
  { pkg: "noto-naskh-arabic", family: "Noto Naskh Arabic", subsets: ["arabic"] },
  { pkg: "noto-sans-devanagari", family: "Noto Sans Devanagari", subsets: ["devanagari"] },
  { pkg: "noto-sans-bengali", family: "Noto Sans Bengali", subsets: ["bengali"] },
  { pkg: "noto-sans-sinhala", family: "Noto Sans Sinhala", subsets: ["sinhala"] },
  { pkg: "noto-sans-tamil", family: "Noto Sans Tamil", subsets: ["tamil"] },
];

const outDir = join(root, "public", "fonts");
mkdirSync(outDir, { recursive: true });

const faces = [];
const manifest = {};
const licences = [];

for (const font of FONTS) {
  const css = readFileSync(join(pkgDir(font.pkg), "wght.css"), "utf8");
  const version = JSON.parse(readFileSync(join(pkgDir(font.pkg), "package.json"), "utf8")).version;
  licences.push(`${font.family} (from @fontsource-variable/${font.pkg}@${version})\n\n${readFileSync(join(pkgDir(font.pkg), "LICENSE"), "utf8").trim()}`);
  manifest[font.family] = {};
  for (const subset of font.subsets) {
    const block = new RegExp(`/\\* ${font.pkg}-${subset}-wght-normal \\*/\\s*@font-face \\{([^}]*)\\}`).exec(css);
    if (!block) throw new Error(`No ${subset} subset in ${font.pkg}`);
    const weight = /font-weight:\s*([^;]+);/.exec(block[1])[1].trim();
    const range = /unicode-range:\s*([^;]+);/.exec(block[1])[1].trim();
    const file = `${font.pkg}-${subset}.woff2`;
    copyFileSync(join(pkgDir(font.pkg), "files", `${font.pkg}-${subset}-wght-normal.woff2`), join(outDir, file));
    manifest[font.family][subset] = `/fonts/${file}`;
    faces.push(
      `@font-face {\n  font-family: "${font.family}";\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("/fonts/${file}") format("woff2");\n  unicode-range: ${range};\n}`,
    );
  }
}

// The plain zero. One glyph taken from Onest by scripts/build-zero-font.py; see that file for why.
// size-adjust makes it the same height as Atkinson's digits.
faces.unshift(
  `@font-face {\n  font-family: "Pardes Zero";\n  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n  src: url("/fonts/pardes-zero.woff2") format("woff2");\n  unicode-range: U+0030;\n  size-adjust: 96%;\n}`,
);
manifest["Pardes Zero"] = { zero: "/fonts/pardes-zero.woff2" };
{
  const onest = join(root, "node_modules", "@fontsource-variable", "onest");
  const version = JSON.parse(readFileSync(join(onest, "package.json"), "utf8")).version;
  licences.push(`Pardes Zero (the digit zero from Onest, @fontsource-variable/onest@${version}; a modified version under the same licence)\n\n${readFileSync(join(onest, "LICENSE"), "utf8").trim()}`);
}

const header =
  "/* Generated by scripts/copy-fonts.mjs. Do not edit by hand.\n" +
  "   A browser fetches a file only when the page shows a character in its unicode-range. */\n\n";
writeFileSync(join(root, "styles", "fonts.css"), header + faces.join("\n\n") + "\n");
writeFileSync(join(outDir, "OFL.txt"), licences.join("\n\n" + "=".repeat(78) + "\n\n") + "\n");
writeFileSync(
  join(root, "lib", "i18n", "font-files.json"),
  JSON.stringify(manifest, null, 1) + "\n",
);
console.log(`fonts: ${faces.length} files copied to public/fonts`);
