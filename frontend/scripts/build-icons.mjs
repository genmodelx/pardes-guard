// Builds components/icons/generated.tsx from the Phosphor SVG files listed in icons.config.mjs.
// Run with `npm run icons`. The output is committed, so builds do not depend on this script.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CUSTOM, ICONS } from "./icons.config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "node_modules", "@phosphor-icons", "core", "assets");

const pascal = (name) =>
  name
    .split("-")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");

function inner(name, weight) {
  const file = join(assets, weight, weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`);
  if (!existsSync(file)) throw new Error(`Phosphor has no "${name}" in weight "${weight}"`);
  const svg = readFileSync(file, "utf8");
  const m = /^<svg[^>]*viewBox="0 0 256 256"[^>]*>(.*)<\/svg>\s*$/s.exec(svg);
  if (!m) throw new Error(`Unexpected SVG shape in ${file}`);
  if (/<script|on\w+=|href=/i.test(m[1])) throw new Error(`Refusing unexpected markup in ${file}`);
  return m[1];
}

const entries = [];
for (const [name, weights] of Object.entries(ICONS)) {
  entries.push([name, Object.fromEntries(weights.map((w) => [w, inner(name, w)]))]);
}
for (const [name, weights] of Object.entries(CUSTOM)) entries.push([name, weights]);
entries.sort((a, b) => a[0].localeCompare(b[0]));

const lines = [
  "// Generated by scripts/build-icons.mjs from @phosphor-icons/core (MIT). Do not edit by hand.",
  "// To add an icon: list it in scripts/icons.config.mjs, then run `npm run icons`.",
  "",
  'import { createIcon } from "./base";',
  "",
];
for (const [name, weights] of entries) {
  const body = Object.entries(weights)
    .map(([w, markup]) => `  ${w}: ${JSON.stringify(markup)},`)
    .join("\n");
  lines.push(`export const Icon${pascal(name)} = /*#__PURE__*/ createIcon(${JSON.stringify(name)}, {\n${body}\n});`, "");
}

writeFileSync(join(root, "components", "icons", "generated.tsx"), lines.join("\n"));
console.log(`icons: ${entries.length} written to components/icons/generated.tsx`);
